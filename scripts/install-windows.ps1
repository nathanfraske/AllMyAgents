if ($Uninstall) {
    Remove-Shim
    Remove-UserPathEntry -Dir $BinDir
    if (-not $KeepApp) {
        Assert-NotRunning
        Uninstall-App
    }
    Write-Host ''
    Write-Host 'OK  AllMyAgents removed.' -ForegroundColor Green
    Write-Host ''
    Note 'Your agents, journals and settings are still on disk, deliberately. Delete them yourself if'
    Note 'you actually want them gone:'
    Note "  Remove-Item -Recurse '$env:LOCALAPPDATA\direct.cec.allmyagents'"
