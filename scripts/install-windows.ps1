function Write-Shim {
    param([string]$ExePath)
    if (-not (Test-Path -LiteralPath $BinDir)) { New-Item -ItemType Directory -Force -Path $BinDir | Out-Null }

    $lines = @(
        '@echo off'
        "rem $ShimMarker -- do not edit; re-running the installer overwrites this file."
        'rem'
        'rem WHY A SHIM rather than putting the install directory itself on PATH. Two reasons, both'
        'rem practical: the app ships next to its own uninstall.exe, so that directory on PATH would'
        'rem make `uninstall` a global command in every terminal on the machine; and the binary is'
        'rem named for the crate, so the directory would give you `allmyagents-desktop` rather than'
        'rem the name anyone would type. A shim also survives the app moving between the per-user and'
        'rem per-machine layouts without the PATH entry going stale.'
        'setlocal'
        "set `"AMA_EXE=$ExePath`""
        ''
        'rem --help before the exists check, deliberately: asking a broken command what it does is'
        'rem exactly when you need it to answer. --version reads the binary, so it comes after.'
        'if /i "%~1"=="--help"    goto :help'
        'if /i "%~1"=="-h"        goto :help'
        'if /i "%~1"=="/?"        goto :help'
        ''
        'if not exist "%AMA_EXE%" goto :missing'
        ''
        'if /i "%~1"=="--version" goto :version'
        'if /i "%~1"=="-v"        goto :version'
        ''
        'rem The empty "" is the window TITLE argument, not padding. Without it cmd takes the first'
        'rem quoted token as a title, and then opens an empty console window instead of the app.'
        'start "" "%AMA_EXE%" %*'
        'exit /b 0'
        ''
        ':version'
        'rem Full path to powershell.exe: this has to work from a shell with a minimal PATH too.'
        '"%SystemRoot%\System32\WindowsPowerShell\v1.0\powershell.exe" -NoProfile -NonInteractive -Command "(Get-Item -LiteralPath $env:AMA_EXE).VersionInfo.ProductVersion"'
        'exit /b %errorlevel%'
        ''
        ':help'
        'echo allmyagents - start the AllMyAgents desktop app.'
        'echo.'
        'echo   allmyagents             Start the app.'
        'echo   allmyagents --version   Print the installed version.'
        'echo.'
        'echo Anything else is passed through to the app.'
        'exit /b 0'
        ''
        ':missing'
        'rem Redirect FIRST. `echo text 1>&2` puts the space before the 1 into the output, so every'
        'rem line ends in a stray blank -- cmd takes the redirection off the end, not out of the middle.'
        '>&2 echo allmyagents: %AMA_EXE% is not there any more.'
        '>&2 echo Reinstall, or repair just this command, with:'
        '>&2 echo   irm https://raw.githubusercontent.com/nathanfraske/AllMyAgents/main/scripts/install-windows.ps1 ^| iex'
        'exit /b 1'
    )

    # ASCII, and CRLF. A .cmd file saved as UTF-8 WITH a BOM makes cmd try to run the BOM bytes as
    # part of the first command -- it reports the mojibake back at you and says it is not recognised
    # as a command -- and Set-Content/Out-File are exactly the cmdlets that add one. WriteAllText with
    # an explicit encoding cannot. (This file is kept ASCII-only for the same family of reason:
    # PowerShell 5.1 reads a .ps1 with no BOM as the system ANSI codepage, not UTF-8.)
    [System.IO.File]::WriteAllText($ShimPath, (($lines -join "`r`n") + "`r`n"), [System.Text.Encoding]::ASCII)
    Say "Installed the '$CmdName' command to $ShimPath"
}

function Remove-Shim {
    if (-not (Test-Path -LiteralPath $ShimPath)) { return }
    # Never delete a file we did not write, even when it has our name. An uninstaller that removes
    # somebody else's script is a worse outcome than one that leaves litter behind.
    $text = Get-Content -LiteralPath $ShimPath -Raw -ErrorAction SilentlyContinue
    if ($text -and $text.Contains($ShimMarker)) {
        Remove-Item -LiteralPath $ShimPath -Force
        Say "Removed $ShimPath"
        $left = @(Get-ChildItem -LiteralPath $BinDir -Force -ErrorAction SilentlyContinue)
        if ($left.Count -eq 0) { Remove-Item -LiteralPath $BinDir -Force -ErrorAction SilentlyContinue }
    } else {
        Warn "left $ShimPath alone -- it has no installer marker in it, so it is not ours."
    }
}

