}

$installed = Get-InstalledApp

if (-not $PathOnly) {
    if ($Msi -and -not (Test-Elevated)) {
        Die @"
-Msi needs an elevated shell.

The .msi is a per-machine package: its Property table sets ALLUSERS=1 and it installs into
Program Files, which needs administrator rights. msiexec /qn cannot show a UAC prompt, so it would
fail rather than ask.

Either run this from an elevated PowerShell, or drop -Msi and use the default installer, which is
per-user, lands in %LOCALAPPDATA%\AllMyAgents, and needs no elevation at all.
"@
    }

    $release = Get-Release
    $version = $release.tag_name
    Say "Latest release: $version"

    # Idempotency: a second run of the same command should be a no-op for the app and still repair
    # the command and the PATH entry, rather than reinstalling 28 MB or failing with MSI error 1638.
    if ((Test-SameVersion -Tag $version -Installed $installed.Version) -and -not $Force) {
        Say "$AppName $($installed.Version) is already installed -- skipping the download. Pass -Force to reinstall."
    } else {
        # The MSI and the -setup.exe are separate products to Windows: separate uninstall entries,
        # separate install directories, separate updater state. Installing one over the other leaves
        # two copies that both auto-update and fight over the hub's port, which presents as the app
        # "randomly" being the wrong version. Refuse to be the cause of that without being told to.
        $switchingKind = $installed -and (($installed.Kind -eq 'nsis' -and $Msi) -or ($installed.Kind -eq 'msi' -and -not $Msi))
        if ($switchingKind -and -not $Force) {
            $other = $(if ($Msi) { 'the MSI' } else { 'the default per-user installer' })
            Die "$AppName $($installed.Version) is already installed as a $($installed.Kind) package ($($installed.Scope)) at $($installed.InstallLocation). Installing it again with $other gives you two independent copies. Remove the existing one first with -Uninstall, or pass -Force if you really want both."
        }
        Assert-NotRunning

        $asset = Select-Asset -Release $release
        $tmp = Join-Path ([System.IO.Path]::GetTempPath()) ("allmyagents-" + [Guid]::NewGuid().ToString('N'))
        New-Item -ItemType Directory -Force -Path $tmp | Out-Null
        try {
            $pkg = Join-Path $tmp $asset.name
            Get-Asset -Asset $asset -Destination $pkg
            Say "Installing $version..."
            Install-Package -Path $pkg
        } finally {
            Remove-Item -Recurse -Force -LiteralPath $tmp -ErrorAction SilentlyContinue
        }
        $installed = Get-InstalledApp
    }
}

$exe = Find-Exe -Installed $installed
if (-not $exe) {
