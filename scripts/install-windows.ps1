function Get-InstalledApp {
    $keys = @(
        'HKCU:\Software\Microsoft\Windows\CurrentVersion\Uninstall\*'
        'HKLM:\Software\Microsoft\Windows\CurrentVersion\Uninstall\*'
        'HKLM:\Software\WOW6432Node\Microsoft\Windows\CurrentVersion\Uninstall\*'
    )
    $found = Get-ItemProperty -Path $keys -ErrorAction SilentlyContinue |
             Where-Object { $_.DisplayName -eq $AppName } |
             Select-Object -First 1
    if (-not $found) { return $null }

    # NSIS writes InstallLocation WITH literal double quotes around it -- verified on a real install,
    # where the value is "C:\Users\...\AppData\Local\AllMyAgents" quotes included. Join-Path on that
    # produces a path containing a quote character, which then fails Test-Path for reasons that look
    # nothing like the cause.
    $loc = ''
    if ($found.InstallLocation) { $loc = ([string]$found.InstallLocation).Trim('"').TrimEnd('\') }

    # An MSI registers under its ProductCode GUID and uninstalls through msiexec; NSIS registers
    # under a plain name and ships its own uninstall.exe. They need different uninstall commands.
    $kind = 'nsis'
    if ($found.PSChildName -match '^\{[0-9A-Fa-f-]{36}\}$') { $kind = 'msi' }

    return [pscustomobject]@{
        Version         = [string]$found.DisplayVersion
        InstallLocation = $loc
        UninstallString = [string]$found.UninstallString
        ProductCode     = [string]$found.PSChildName
        Kind            = $kind
        Scope           = $(if ($found.PSPath -like '*HKEY_CURRENT_USER*') { 'per-user' } else { 'per-machine' })
    }
}

function Test-SameVersion {
    param([string]$Tag, [string]$Installed)
    if (-not $Installed -or -not $Tag) { return $false }
    # These two never match raw. The git tag carries the pre-release suffix (v0.1.4-alpha.5) while the
    # registry carries the numeric version the bundler used (0.1.4), because MSI/WiX rejects semver
    # pre-release suffixes -- see the comment on `version` in apps/desktop/src-tauri/Cargo.toml. The
    # obvious workaround, a substring wildcard, matches 0.1.1 against 0.1.14 and skips a real upgrade.
    $t = ($Tag -replace '^[vV]', '') -replace '-.*$', ''
    try { return ([version]$t -eq [version]$Installed) } catch { return ($t -eq $Installed) }
}

function Find-Exe {
    param($Installed)
    if ($Installed -and $Installed.InstallLocation) {
        $candidate = Join-Path $Installed.InstallLocation $ExeName
        if (Test-Path -LiteralPath $candidate) { return $candidate }
    }
    $roots = @(
        (Join-Path $env:LOCALAPPDATA $AppName)
        (Join-Path $env:LOCALAPPDATA "Programs\$AppName")
        (Join-Path $env:ProgramFiles $AppName)
    ) | Where-Object { $_ -and (Test-Path -LiteralPath $_) }
    foreach ($r in $roots) {
        $hit = Get-ChildItem -LiteralPath $r -Filter $ExeName -Recurse -ErrorAction SilentlyContinue |
               Select-Object -First 1
        if ($hit) { return $hit.FullName }
    }
    return $null
}

function Assert-NotRunning {
    $running = @(Get-Process -Name $ProcName -ErrorAction SilentlyContinue)
    if ($running.Count -eq 0) { return }
    if ($Force) {
        Warn "$AppName is running; -Force was given, so continuing. The installer may close it."
        return
    }
    Die "$AppName is running (pid $($running[0].Id)). Quit it first, or pass -Force. Installing over a running app can leave a half-replaced install and will interrupt any chat mid-turn."
}

