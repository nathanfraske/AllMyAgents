    Warn "could not find $ExeName. What is actually in the likely places:"
    foreach ($r in @((Join-Path $env:LOCALAPPDATA $AppName), (Join-Path $env:LOCALAPPDATA 'Programs'), $env:ProgramFiles)) {
        if ($r -and (Test-Path -LiteralPath $r)) {
            Get-ChildItem -LiteralPath $r -Filter '*llmy*' -Recurse -Depth 2 -ErrorAction SilentlyContinue |
                Select-Object -First 20 | ForEach-Object { Note $_.FullName }
        }
    }
    Die 'the app is not where this script expected it. Nothing was changed on your PATH.'
}

Write-Host ''
