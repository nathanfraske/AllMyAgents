<#
    Install AllMyAgents on Windows from a terminal, and put an `allmyagents` command on the PATH.

      irm https://raw.githubusercontent.com/nathanfraske/AllMyAgents/main/scripts/install-windows.ps1 | iex

    To pass options through that one-liner, `iex` is not enough -- it evaluates a string and has
    nowhere to put arguments. Build a scriptblock instead:

      & ([scriptblock]::Create((irm https://raw.githubusercontent.com/nathanfraske/AllMyAgents/main/scripts/install-windows.ps1))) -Uninstall

    Or, better, keep the file so you can read it before running it and re-run it later:

      irm https://raw.githubusercontent.com/nathanfraske/AllMyAgents/main/scripts/install-windows.ps1 -OutFile install-allmyagents.ps1
      notepad install-allmyagents.ps1
      .\install-allmyagents.ps1

    WHY THE DEFAULT IS THE -setup.exe AND NOT THE .msi.

    The MSI is a PER-MACHINE package. Read straight out of its Property table: ALLUSERS=1, and
    INSTALLDIR's parent in the Directory table is ProgramFiles64Folder. A per-machine install into
    Program Files needs administrator rights, and `msiexec /qn` cannot show a UAC prompt -- it just
    fails, from a shell the user opened normally. So the MSI cannot be the default for an installer
    whose whole selling point is that it needs no elevation.

    The NSIS -setup.exe is built with installMode: currentUser (see tauri.conf.json), lands in
    %LOCALAPPDATA%\AllMyAgents, and needs no elevation at all. It is also what the alpha testers
    already have installed. That is the default here; -Msi opts into the other one and says plainly
    that you need an elevated shell for it.

    WHAT IT DOES NOT DO. The build has no Authenticode certificate, so SmartScreen warns on first
    launch and this script cannot verify a publisher signature. It checks what it can -- the exact
    byte count GitHub reported for the asset, and the file's magic bytes -- and prints the SHA-256 so
    you can compare it against the release page. If you did not get this URL from the AllMyAgents
    repo, stop.

    Re-running is safe. It skips the download when the same version is already installed, rewrites
    the shim unconditionally, and will not add a second copy of the PATH entry.
#>

[CmdletBinding()]
param(
    # Defaults come from the environment as well as the parameter list, because the `irm | iex`
    # one-liner above can set environment variables and cannot set parameters.
    [string]$Tag    = $env:AMA_TAG,
    [string]$Repo   = $(if ($env:AMA_REPO) { $env:AMA_REPO } else { 'nathanfraske/AllMyAgents' }),
    [string]$BinDir = $env:AMA_BIN_DIR,

    [switch]$Msi,
    [switch]$Uninstall,
    [switch]$KeepApp,
    [switch]$PathOnly,
    [switch]$NoPath,
    [switch]$Force,
    [switch]$Help
)

$ErrorActionPreference = 'Stop'

# Invoke-WebRequest in Windows PowerShell renders a progress bar per chunk, and on a 28 MB download
# that rendering costs more wall-clock time than the transfer. Turning it off is worth roughly 10x.
$ProgressPreference = 'SilentlyContinue'

# Windows PowerShell picks its TLS versions from a machine-wide default that on older or hardened
# boxes still excludes TLS 1.2, which is the only thing github.com accepts. The resulting error is
# "The request was aborted: Could not create SSL/TLS secure channel" -- which reads like a broken
# network rather than a protocol default, and sends people to the wrong place entirely.
[Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12

$AppName  = 'AllMyAgents'
$CmdName  = 'allmyagents'

# THE INSTALLED BINARY IS NAMED FOR THE CRATE, NOT FOR productName. tauri.conf.json sets no
# mainBinaryName, so the bundler uses the Cargo package name (allmyagents-desktop). Verified three
# ways before this file was written: the crate name in apps/desktop/src-tauri/Cargo.toml, the File
# table of a locally built MSI, and the actual file on disk in an existing install. Assuming
# "AllMyAgents.exe" has now caused two separate bugs in this repo, so it is written down here.
$ExeName  = 'allmyagents-desktop.exe'
$ProcName = 'allmyagents-desktop'

# How the installer recognises its own past work, so that re-running never duplicates anything and
# uninstalling never deletes a file somebody else put there.
$ShimMarker = 'generated by the AllMyAgents installer'

if (-not $BinDir) { $BinDir = Join-Path $env:LOCALAPPDATA 'AllMyAgents\bin' }
$ShimPath = Join-Path $BinDir "$CmdName.cmd"

# `exit` is what makes a CI step fail, and this script must not swallow that. But under
# `irm ... | iex` there is no script to exit from, so `exit` would close the user's PowerShell window
# over something as ordinary as a rate limit. $PSCommandPath is set only when running from a file.
$FromFile = [bool]$PSCommandPath

function Say  { param([string]$m) Write-Host "==> $m" -ForegroundColor Cyan }
function Note { param([string]$m) Write-Host "    $m" }
function Warn { param([string]$m) Write-Host "warning: $m" -ForegroundColor Yellow }
function Die {
    param([string]$m)
    Write-Host ''
    Write-Host "error: $m" -ForegroundColor Red
    if ($FromFile) { exit 1 } else { throw $m }
}

function Show-Usage {
    Write-Host @'
Install AllMyAgents on Windows and put an `allmyagents` command on your PATH.

  .\install-windows.ps1                Install the latest release (no elevation needed).
  .\install-windows.ps1 -Msi           Use the .msi instead. Needs an elevated shell: the MSI is a
                                       per-machine package that installs into Program Files.
  .\install-windows.ps1 -PathOnly      Leave the app alone; just (re)create the allmyagents command.
  .\install-windows.ps1 -NoPath        Install the app only. No command, no PATH change.
  .\install-windows.ps1 -Uninstall     Remove the app, the command, and the PATH entry.
  .\install-windows.ps1 -Uninstall -KeepApp
                                       Remove only the command and the PATH entry.
  .\install-windows.ps1 -Force         Reinstall even if this version is already installed, and
                                       proceed even if the app is running.
  -Tag v0.1.4-alpha.5                  Install a specific release.
  -BinDir C:\path                      Put the allmyagents command somewhere else.

Environment: AMA_TAG, AMA_REPO, AMA_BIN_DIR, GITHUB_TOKEN (optional; raises GitHub's
anonymous API limit of 60 requests/hour).
'@
}

function Test-Elevated {
    $id = [Security.Principal.WindowsIdentity]::GetCurrent()
    $principal = New-Object Security.Principal.WindowsPrincipal($id)
    return $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
}

# ---------------------------------------------------------------------------------------------
# USER PATH
#
# The string handling lives in two pure functions so it can be tested without touching a registry,
# because every bug in this area is a string bug: an entry that differs only by a trailing backslash
# or by case, an empty entry from a stray semicolon, a value appended twice by a second run.
# ---------------------------------------------------------------------------------------------

function Test-PathContains {
    param([string]$RawPath, [string]$Dir)
    $want = $Dir.TrimEnd('\')
    foreach ($p in ($RawPath -split ';')) {
        if ($p -eq '') { continue }
        # Windows paths are case-insensitive and treat a trailing separator as the same directory, so
        # a literal string match would happily add C:\x\bin next to an existing C:\X\bin\.
        if ($p.TrimEnd('\').Equals($want, [StringComparison]::OrdinalIgnoreCase)) { return $true }
    }
    return $false
}

function Add-ToPathString {
    param([string]$RawPath, [string]$Dir)
    if (Test-PathContains -RawPath $RawPath -Dir $Dir) { return $RawPath }
    # Append only. Round-tripping the value through a split/filter/join would also "tidy" things we
    # were never asked to touch -- an empty entry from a double semicolon, ordering, spacing -- and a
    # PATH is not a file to reformat while you are in there.
    if ($RawPath -eq '') { return $Dir }
    if ($RawPath.EndsWith(';')) { return ($RawPath + $Dir) }
    return ($RawPath + ';' + $Dir)
}

function Remove-FromPathString {
    param([string]$RawPath, [string]$Dir)
    $want = $Dir.TrimEnd('\')
    $kept = New-Object System.Collections.ArrayList
    foreach ($p in ($RawPath -split ';')) {
        if ($p -ne '' -and $p.TrimEnd('\').Equals($want, [StringComparison]::OrdinalIgnoreCase)) { continue }
        [void]$kept.Add($p)
    }
    return ($kept -join ';')
}

function Get-UserPath {
    $key = [Microsoft.Win32.Registry]::CurrentUser.OpenSubKey('Environment')
    if (-not $key) { return @{ Value = ''; Kind = 'String' } }
    try {
        if (-not ($key.GetValueNames() -contains 'Path')) { return @{ Value = ''; Kind = 'String' } }
        # DoNotExpandEnvironmentNames is the important part. A user PATH may legitimately contain
        # %USERPROFILE%\bin; reading it the ordinary way hands back the expanded text, and writing
        # that back bakes today's expansion in permanently. The indirection is gone and nobody
        # notices until the variable it depended on changes.
        return @{
            Value = $key.GetValue('Path', '', [Microsoft.Win32.RegistryValueOptions]::DoNotExpandEnvironmentNames)
            Kind  = $key.GetValueKind('Path').ToString()
        }
    } finally { $key.Close() }
}

function Send-EnvironmentChange {
    # A direct registry write changes the stored value but tells nobody. Explorer -- and therefore
    # every program a user starts from it -- keeps the old environment until they sign out.
    # SetEnvironmentVariable broadcasts this message itself; when we have to bypass it (below) we
    # have to send it ourselves.
    if (-not ('Ama.Native' -as [type])) {
        Add-Type -Namespace 'Ama' -Name 'Native' -MemberDefinition @'
[DllImport("user32.dll", SetLastError = true, CharSet = CharSet.Auto)]
public static extern IntPtr SendMessageTimeout(
    IntPtr hWnd, uint Msg, UIntPtr wParam, string lParam,
    uint fuFlags, uint uTimeout, out UIntPtr lpdwResult);
'@
    }
    $result = [UIntPtr]::Zero
    # HWND_BROADCAST, WM_SETTINGCHANGE, SMTO_ABORTIFHUNG, 5s -- a hung top-level window must not be
    # able to wedge an installer.
    [void][Ama.Native]::SendMessageTimeout([IntPtr]0xffff, 0x1A, [UIntPtr]::Zero, 'Environment', 2, 5000, [ref]$result)
}

function Set-UserPath {
    param([string]$Value, [string]$Kind)
    if ($Kind -eq 'ExpandString') {
        # [Environment]::SetEnvironmentVariable writes REG_SZ -- confirmed by experiment on this
        # repo's dev machine, storing "%USERPROFILE%\x" and reading the value kind back as String.
        # Using it on a PATH that is currently REG_EXPAND_SZ therefore converts the type, and every
        # %VAR% entry in it stops expanding from that moment on, for every process on the machine,
        # with no error anywhere. So the documented API is the right tool for the common case and the
        # wrong one here; write it ourselves and send the notification the API would have sent.
        $key = [Microsoft.Win32.Registry]::CurrentUser.OpenSubKey('Environment', $true)
        try { $key.SetValue('Path', $Value, [Microsoft.Win32.RegistryValueKind]::ExpandString) }
        finally { $key.Close() }
        Send-EnvironmentChange
    } else {
        # NEVER $env:Path here. That is the PROCESS environment: the machine PATH, the user PATH and
        # anything this session added, already merged into one string. Writing it back into the User
        # scope copies the whole machine PATH into the user's copy, permanently, and every entry then
        # appears twice in every process started afterwards.
        [Environment]::SetEnvironmentVariable('Path', $Value, 'User')
    }
}

function Add-UserPathEntry {
    param([string]$Dir)
    $cur = Get-UserPath
    if (Test-PathContains -RawPath $cur.Value -Dir $Dir) {
        Say "$Dir is already on your user PATH."
        return
    }
    $new = Add-ToPathString -RawPath $cur.Value -Dir $Dir
    Set-UserPath -Value $new -Kind $cur.Kind

    # Read it back rather than trusting the write. Losing a PATH is expensive to undo by hand, and a
    # silent no-op here would show up much later as "the command does not exist".
    $after = Get-UserPath
    if (-not (Test-PathContains -RawPath $after.Value -Dir $Dir)) {
        Die "wrote the user PATH but $Dir is not in it afterwards. Nothing was lost -- add it yourself via System Properties > Environment Variables."
    }
    Say "Added $Dir to your user PATH (per-user; no administrator rights involved)."
    Note 'Already-open terminals keep the environment they started with -- open a new one.'
}

function Remove-UserPathEntry {
    param([string]$Dir)
    $cur = Get-UserPath
    if (-not (Test-PathContains -RawPath $cur.Value -Dir $Dir)) { return }
    Set-UserPath -Value (Remove-FromPathString -RawPath $cur.Value -Dir $Dir) -Kind $cur.Kind
    Say "Removed $Dir from your user PATH."
}

