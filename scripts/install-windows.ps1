function Get-Release {
    $api = "https://api.github.com/repos/$Repo/releases/latest"
    if ($Tag) { $api = "https://api.github.com/repos/$Repo/releases/tags/$Tag" }

    # The GitHub API rejects requests with no User-Agent outright, with a 403 that looks exactly like
    # a rate limit. Send one.
    $headers = @{ 'User-Agent' = 'allmyagents-installer'; 'Accept' = 'application/vnd.github+json' }
    if ($env:GITHUB_TOKEN) { $headers['Authorization'] = "Bearer $env:GITHUB_TOKEN" }

    try {
        return Invoke-RestMethod -Uri $api -Headers $headers -UseBasicParsing -TimeoutSec 30
    } catch {
        # Branch on the STATUS. "it failed" and "you are offline" are not the same thing, and the
        # macOS installer already had to learn this the hard way: it reported every failure as a
        # connection problem, and the first one CI actually hit was a 403 rate limit on a machine
        # with perfect connectivity.
        $code = 0
        if ($_.Exception.PSObject.Properties['Response'] -and $_.Exception.Response) {
            $code = [int]$_.Exception.Response.StatusCode
        }
        if ($code -eq 403 -or $code -eq 429) {
            Die "GitHub rate-limited this machine (HTTP $code). This is not a connection problem -- the limit is 60 requests/hour per IP ADDRESS, so a corporate NAT, a university or a VPN shares it with everyone else on that address. It resets within the hour. Set GITHUB_TOKEN to a personal access token to raise it."
        }
        if ($code -eq 404) { Die "no release named '$Tag' exists in $Repo." }
        if ($code -eq 0)   { Die "could not reach api.github.com at all. Check your internet connection or proxy. ($($_.Exception.Message))" }
        Die "GitHub returned HTTP $code looking up the release."
    }
}

function Select-Asset {
    param($Release)

    # PROCESSOR_ARCHITECTURE reports the architecture of THIS PROCESS, so a 32-bit PowerShell on a
    # 64-bit machine says x86. PROCESSOR_ARCHITEW6432 is set only in that case and holds the real one.
    $arch = $env:PROCESSOR_ARCHITECTURE
    if ($env:PROCESSOR_ARCHITEW6432) { $arch = $env:PROCESSOR_ARCHITEW6432 }
    $isArm = ($arch -eq 'ARM64')

    $suffix = 'x64-setup.exe'
    $armSuffix = 'arm64-setup.exe'
    if ($Msi) { $suffix = '_x64_en-US.msi'; $armSuffix = '_arm64_en-US.msi' }

    $assets = @($Release.assets)
    # A ".sig" is the updater's minisign signature over the artifact, not an artifact. Suffix matching
    # already excludes them, but only by luck of the naming, so be explicit.
    $assets = $assets | Where-Object { -not $_.name.EndsWith('.sig') }

    if ($isArm) {
        $hit = $assets | Where-Object { $_.name.EndsWith($armSuffix) } | Select-Object -First 1
        if ($hit) { return $hit }
    }
    $hit = $assets | Where-Object { $_.name.EndsWith($suffix) } | Select-Object -First 1
    if ($hit -and $isArm) {
        # Not a guess: Windows on ARM runs x64 binaries under emulation. Say so rather than silently
        # installing something that does not match the machine.
        Note 'No arm64 build in this release; using the x64 one, which Windows on ARM runs emulated.'
    }
    if (-not $hit) {
        $names = ($assets | ForEach-Object { $_.name }) -join ', '
        Die "release $($Release.tag_name) has no asset ending in '$suffix'. It has: $names"
    }
    return $hit
}

function Get-Asset {
    param($Asset, [string]$Destination)

    $mb = [math]::Round($Asset.size / 1MB, 1)
    Say "Downloading $($Asset.name) ($mb MB)..."

    # Deliberately NO Authorization header on this request, even when GITHUB_TOKEN is set. Asset URLs
    # redirect to objects.githubusercontent.com, Windows PowerShell forwards request headers across
    # the redirect, and that host rejects a GitHub token with a 400 -- so authenticating a download
    # that needs no authentication is how you break it.
    try {
        Invoke-WebRequest -Uri $Asset.browser_download_url -OutFile $Destination -UseBasicParsing -TimeoutSec 900 `
            -Headers @{ 'User-Agent' = 'allmyagents-installer' }
    } catch {
        Die "download failed: $($_.Exception.Message)"
    }

    $actual = (Get-Item -LiteralPath $Destination).Length
    if ($Asset.size -gt 0 -and $actual -ne $Asset.size) {
        Die "downloaded $actual bytes but GitHub said the asset is $($Asset.size). Truncated or intercepted -- do not run it."
    }

    # Magic bytes. Without this check the commonest failure -- a proxy or captive portal answering
    # with an HTML error page -- lands as a file with the right name and the right extension that
    # msiexec then rejects with something unhelpful about the package being invalid.
    $head = New-Object byte[] 8
    $fs = [System.IO.File]::OpenRead($Destination)
    try { [void]$fs.Read($head, 0, 8) } finally { $fs.Close() }
    $hex = ($head | ForEach-Object { $_.ToString('X2') }) -join ''
    if ($Destination.EndsWith('.msi')) {
        # OLE2 compound document.
        if (-not $hex.StartsWith('D0CF11E0A1B11AE1')) { Die "that is not an MSI (file starts with $hex). Do not run it." }
    } else {
        # PE executable: "MZ".
        if (-not $hex.StartsWith('4D5A')) { Die "that is not a Windows executable (file starts with $hex). Do not run it." }
    }

    $sha = (Get-FileHash -LiteralPath $Destination -Algorithm SHA256).Hash
    Note "size $actual bytes, as published"
    Note "SHA-256 $sha"

    # There is no Authenticode certificate for this project yet, so this will say NotSigned and that
    # is expected, not a warning to bury. Report it rather than pretending it was checked.
    $sig = Get-AuthenticodeSignature -LiteralPath $Destination
    if ($sig.Status -eq 'Valid') {
        Note "signed by $($sig.SignerCertificate.Subject)"
    } else {
        Note "not code-signed ($($sig.Status)) -- expected for this project today; SmartScreen will warn on first launch."
    }
}

# ---------------------------------------------------------------------------------------------
# Installing and uninstalling the app itself
# ---------------------------------------------------------------------------------------------

function Install-Package {
    param([string]$Path)

    if ($Path.EndsWith('.msi')) {
        $log = Join-Path $env:TEMP 'allmyagents-msi.log'
        # An ARRAY, and with the quotes written INTO the element. Start-Process joins -ArgumentList
        # with spaces and adds no quoting of its own, so a %TEMP% under a profile name with a space
        # in it silently becomes two arguments. This is the same class of bug that ate a
        # --config '{"json":true}' argument in this repo's CI: PowerShell's handling of quotes when
        # handing arguments to a native command is not what it looks like.
        $msiArgs = @('/i', "`"$Path`"", '/qn', '/norestart', '/l*v', "`"$log`"")
        $p = Start-Process msiexec.exe -ArgumentList $msiArgs -Wait -PassThru
        switch ($p.ExitCode) {
            0     { Say 'Installed.' }
            3010  { Say 'Installed. Windows wants a restart to finish, but the app will run now.' }
            1602  { Die 'the installation was cancelled.' }
            1618  { Die 'another Windows Installer job is already running. Wait for it to finish and try again.' }
            1625  { Die 'system policy blocks non-administrators from installing this package. Run from an elevated shell, or use the default (non-MSI) installer, which needs no elevation.' }
            1638  { Die "this exact version is already installed. Pass -Force to reinstall it." }
            default {
                if (Test-Path $log) { Get-Content $log -Tail 40 | ForEach-Object { Write-Host "    $_" } }
                Die "msiexec failed with exit code $($p.ExitCode). Full log: $log"
            }
        }
    } else {
        # NSIS: /S is silent. tauri.conf.json sets installMode currentUser, so this lands in
        # %LOCALAPPDATA%\AllMyAgents and asks for nothing.
        $p = Start-Process -FilePath $Path -ArgumentList '/S' -Wait -PassThru
        if ($p.ExitCode -ne 0) { Die "the installer exited with code $($p.ExitCode)." }
        Say 'Installed.'
    }
}

function Uninstall-App {
    $installed = Get-InstalledApp
    if (-not $installed) { Note "$AppName does not appear to be installed."; return }

    Say "Removing $AppName $($installed.Version) ($($installed.Kind), $($installed.Scope))..."
    if ($installed.Kind -eq 'msi') {
        if ($installed.Scope -eq 'per-machine' -and -not (Test-Elevated)) {
            Die "removing a per-machine MSI install needs an elevated shell. Open PowerShell as administrator and run this again, or use Settings > Apps."
        }
        $p = Start-Process msiexec.exe -ArgumentList @('/x', $installed.ProductCode, '/qn', '/norestart') -Wait -PassThru
        if ($p.ExitCode -ne 0 -and $p.ExitCode -ne 3010) { Die "msiexec /x failed with exit code $($p.ExitCode)." }
    } else {
        $exe = $installed.UninstallString.Trim('"')
        if (-not (Test-Path -LiteralPath $exe)) { Die "the registered uninstaller is missing: $exe. Remove it via Settings > Apps." }
        $p = Start-Process -FilePath $exe -ArgumentList '/S' -Wait -PassThru
        if ($p.ExitCode -ne 0) { Die "the uninstaller exited with code $($p.ExitCode)." }
    }
    Say 'Removed.'
}

